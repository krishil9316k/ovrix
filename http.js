import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { createWebhookServer } from '../lib/webhooks.js';
const got = [];
const cfg = { stripeWebhookSecret: 'whsec', razorpayWebhookSecret: '' };
const srv = createWebhookServer({ cfg, onEvent: async (e) => got.push(e), log: { error() {} } });
await new Promise((r) => srv.listen(0, r));
const base = `http://127.0.0.1:${srv.address().port}`;
const body = JSON.stringify({ id: 'evt_1', type: 'checkout.session.completed', data: { object: { id: 'cs', payment_status: 'paid', amount_total: 100, currency: 'usd', customer_email: 'a@b.com' } } });
const t = Math.floor(Date.now() / 1000);
const sig = `t=${t},v1=${crypto.createHmac('sha256', 'whsec').update(`${t}.${body}`).digest('hex')}`;
const post = (p, b, h = {}) => fetch(base + p, { method: 'POST', body: b, headers: h });
assert.equal((await post('/webhooks/stripe', body, { 'stripe-signature': sig })).status, 200);
assert.equal(got.length, 1);
assert.equal((await post('/webhooks/stripe', body, { 'stripe-signature': 't=1,v1=bad' })).status, 400);
assert.equal((await post('/webhooks/stripe', body)).status, 400);
assert.equal((await post('/webhooks/razorpay', body, { 'x-razorpay-signature': 'x' })).status, 503);
assert.equal((await post('/nope', body)).status, 404);
assert.equal((await fetch(base + '/health')).status, 200);
assert.equal((await fetch(base + '/webhooks/stripe')).status, 405);
srv.close();
console.log('✅ Webhook HTTP server checks passed');
